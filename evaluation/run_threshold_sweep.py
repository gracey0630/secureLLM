"""
evaluation/run_threshold_sweep.py — LLM Guard threshold sweep + SecUtil analysis.

Loads pre-computed LLM Guard scores from logs/b2_scores.csv (generated by
baselines/b2_llmguard.py), re-runs heuristic_scan() on the same corpus for the
B1 reference point, then sweeps thresholds 0.30→0.95 to produce the SecUtil
comparison table and plot.

Finding: the sweep is flat — TPR=1.0 at every threshold. LLM Guard gives attack
inputs scores of exactly 1.0 and most legitimate inputs scores near 0.0, so there
is no threshold-sensitive tradeoff to navigate on HackAPrompt. The meaningful
result is the B0→B1→B2 SecUtil progression, not the curve shape. See report_notes.md.

Outputs:
  results/threshold_sweep.csv   — per-threshold metrics
  results/tradeoff_llmguard.png — SecUtil curve with B0/B1/B2 overlaid

Usage:
    python -m evaluation.run_threshold_sweep
    python -m evaluation.run_threshold_sweep --limit 20    # smoke test
    python -m evaluation.run_threshold_sweep --no-plot     # skip matplotlib
"""

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent.parent))

from evaluation.metrics import compute_classification_metrics, compute_secutil
from pipeline.input_scanner import heuristic_scan

LOGS_DIR    = Path(__file__).parent.parent / "logs"
RESULTS_DIR = Path(__file__).parent.parent / "results"
RESULTS_DIR.mkdir(exist_ok=True)

THRESHOLDS = np.linspace(0.30, 0.95, 14)  # includes 0.50 (B2 operating point)
B2_THRESHOLD = 0.50                         # threshold used in b2_llmguard.py


# ── Data loading ───────────────────────────────────────────────────────────────

def load_scores(limit: int | None = None) -> pd.DataFrame:
    """
    Load pre-computed LLM Guard scores from logs/b2_scores.csv.
    Exits with a clear message if the cache is missing rather than
    silently triggering a 45-60 min re-scoring run.
    """
    path = LOGS_DIR / "b2_scores.csv"
    if not path.exists():
        print(f"ERROR: {path} not found.")
        print("Generate it first:  python baselines/b2_llmguard.py  (~45-60 min)")
        sys.exit(1)

    df = pd.read_csv(path)
    if limit:
        # Keep proportional attack/legit split for smoke tests
        attacks = df[df["label"] == 1].head(int(limit * 1583 / 2314))
        legit   = df[df["label"] == 0].head(int(limit * 731  / 2314))
        df = pd.concat([attacks, legit]).reset_index(drop=True)

    n_attacks = (df["label"] == 1).sum()
    n_legit   = (df["label"] == 0).sum()
    print(f"Loaded {len(df)} rows from cache  (attacks={n_attacks}  legit={n_legit})")
    return df


# ── Reference points ───────────────────────────────────────────────────────────

def compute_b0() -> dict:
    """B0: unprotected — nothing is ever blocked."""
    return {"tpr": 0.0, "fpr": 0.0, "precision": 0.0, "f1": 0.0, "secutil": 0.0}


def compute_b1(texts: list[str], labels: list[int]) -> dict:
    """
    B1: heuristic scanner, re-run on the same corpus as the LLM Guard sweep
    so all reference points use identical inputs.
    """
    print(f"\nRunning heuristic_scan() on {len(texts)} inputs for B1 reference point...")
    y_pred = []
    for i, text in enumerate(texts):
        triggered, _ = heuristic_scan(str(text))
        y_pred.append(1 if triggered else 0)
        if (i + 1) % 500 == 0:
            print(f"  {i+1}/{len(texts)}")

    m = compute_classification_metrics(np.array(labels), np.array(y_pred))
    return {**m, "secutil": compute_secutil(m["f1"], m["fpr"])}


# ── Threshold sweep ────────────────────────────────────────────────────────────

def run_sweep(scores: list[float], labels: list[int]) -> pd.DataFrame:
    """
    Sweep thresholds over pre-computed LLM Guard scores.
    Scores come from the cache — no model calls needed.
    """
    y_true    = np.array(labels)
    score_arr = np.array(scores)

    rows = []
    for t in THRESHOLDS:
        y_pred = (score_arr >= t).astype(int)
        m = compute_classification_metrics(y_true, y_pred)
        rows.append({
            "threshold": round(float(t), 4),
            **m,
            "secutil": compute_secutil(m["f1"], m["fpr"]),
        })
    return pd.DataFrame(rows)


# ── Output ─────────────────────────────────────────────────────────────────────

def print_summary(sweep_df: pd.DataFrame, b0: dict, b1: dict) -> None:
    b2_mask  = np.isclose(sweep_df["threshold"], B2_THRESHOLD, atol=0.01)
    b2_row   = sweep_df[b2_mask].iloc[0]
    peak_row = sweep_df.loc[sweep_df["secutil"].idxmax()]

    print("\n" + "=" * 72)
    print("  Threshold Sweep — Results")
    print("=" * 72)
    print(f"  {'Config':<38} {'TPR':>6} {'FPR':>6} {'F1':>6} {'SecUtil':>8}")
    print(f"  {'─'*68}")

    rows = [
        (b0,       "B0 — unprotected"),
        (b1,       "B1 — heuristic scanner"),
        (b2_row,   f"B2 — LLM Guard (t={B2_THRESHOLD:.2f})"),
        (peak_row, f"LLM Guard peak SecUtil (t={peak_row['threshold']:.2f})"),
    ]
    for data, label in rows:
        print(f"  {label:<38} {data['tpr']:>6.3f} {data['fpr']:>6.3f} "
              f"{data['f1']:>6.3f} {data['secutil']:>8.4f}")

    print()
    print("  Finding: sweep is flat — TPR=1.0 at all thresholds 0.30→0.95.")
    print("  LLM Guard scores are binary on HackAPrompt (attacks→1.0, legit→~0.0).")
    fpr_min = sweep_df["fpr"].min()
    fpr_max = sweep_df["fpr"].max()
    print(f"  Threshold choice has limited impact; FPR varies {fpr_max:.3f}→{fpr_min:.3f} as threshold rises.")
    print("  The meaningful result is the B0→B1→B2 SecUtil progression.")
    print("=" * 72)


# ── Main ───────────────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--limit",   type=int,  default=None,
                        help="Cap rows (proportional split kept) — for smoke tests")
    parser.add_argument("--no-plot", action="store_true",
                        help="Skip plot generation")
    args = parser.parse_args()

    df     = load_scores(limit=args.limit)
    texts  = df["text"].tolist()
    labels = df["label"].tolist()
    scores = df["score"].tolist()

    b0       = compute_b0()
    b1       = compute_b1(texts, labels)
    sweep_df = run_sweep(scores, labels)

    # Save sweep table
    out_path = RESULTS_DIR / "threshold_sweep.csv"
    sweep_df.to_csv(out_path, index=False)
    print(f"\nSweep table saved → {out_path}")

    print_summary(sweep_df, b0, b1)

    if not args.no_plot:
        from evaluation.plots import plot_secutil_comparison
        b2_mask = np.isclose(sweep_df["threshold"], B2_THRESHOLD, atol=0.01)
        b2_pt   = sweep_df[b2_mask].iloc[0].to_dict()
        plot_secutil_comparison(sweep_df, b0=b0, b1=b1, b2=b2_pt)


if __name__ == "__main__":
    main()
